"""Generic demo storage contract, independent of the private Sheet schema."""
from typing import Protocol
from job_pipeline.domain.records import PipelineRecord


class RecordStoragePort(Protocol):
    def list_records(self) -> list[PipelineRecord]: ...
    def create(self, fields: dict, stage_id: str | None = None) -> PipelineRecord: ...
    def update(self, record_id: str, fields: dict, stage_id: str) -> None: ...
    def add_activity(self, record_id: str, kind: str, text: str) -> None: ...
    def reset(self) -> None: ...
